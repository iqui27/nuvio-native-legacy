#!/usr/bin/env python3
"""Build the add-on emoji atlas from the upstream Twemoji 14.0.2 tarball.

Usage: python3 tools/emoji-atlas.py /path/to/twemoji-v14.0.2.tar.gz
Requires Pillow only when regenerating assets; no runtime dependency.
"""
import io
import math
from pathlib import Path
import sys
import tarfile
from PIL import Image

root = Path(__file__).resolve().parents[1]
with tarfile.open(sys.argv[1]) as archive:
    entries = []
    for member in archive.getmembers():
        if '/assets/72x72/' not in member.name or not member.name.endswith('.png'):
            continue
        key = Path(member.name).stem
        points = tuple(int(p, 16) for p in key.split('-'))
        # All standalone emoji, country flags, keycaps and skin tones. ZWJ
        # sequences stay out of this small TV subset; add when needed.
        if len(points) == 1 or all(0x1F1E6 <= p <= 0x1F1FF for p in points) or 0x20E3 in points or (len(points) == 2 and 0x1F3FB <= points[-1] <= 0x1F3FF):
            entries.append((points, member))
    entries.sort(key=lambda e: e[0])
    columns = 40
    atlas = Image.new('RGBA', (columns * 32, math.ceil(len(entries) / columns) * 32))
    keys = []
    for i, (points, member) in enumerate(entries):
        pic = Image.open(io.BytesIO(archive.extractfile(member).read())).convert('RGBA')
        atlas.paste(pic.resize((32, 32), Image.Resampling.LANCZOS), ((i % columns) * 32, (i // columns) * 32))
        keys.append('  { ' + ', '.join(f'0x{p:x}' for p in points) + ' },')
    atlas = atlas.quantize(colors=128, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    atlas.save(root / 'deploy/app/fonts/addon-emoji.png', optimize=True)
    (root / 'src/emoji_atlas.h').write_text(
        '// Generated by tools/emoji-atlas.py; Twemoji 14.0.2, CC-BY 4.0.\n'
        f'#define EMOJI_COLUMNS {columns}\n'
        'static const unsigned emojiKeys[][3] = {\n' + '\n'.join(keys) + '\n};\n')
    license_text = archive.extractfile('twemoji-14.0.2/LICENSE-GRAPHICS').read()
    (root / 'deploy/app/fonts/addon-emoji-LICENSE.txt').write_bytes(
        b'Twemoji 14.0.2 graphics by Twitter, Inc. and contributors.\n'
        b'https://github.com/twitter/twemoji/tree/v14.0.2\n'
        b'Modifications: resized to 32px and packed into an atlas.\n\n' + license_text)
print(f'{len(entries)} emoji; {atlas.width}x{atlas.height}; {len((root / "deploy/app/fonts/addon-emoji.png").read_bytes())} PNG bytes')
