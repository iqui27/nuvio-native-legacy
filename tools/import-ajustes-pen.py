#!/usr/bin/env python3
"""Import approved advanced row geometry and key bindings, never mock values."""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
source = pathlib.Path(sys.argv[1])
frames = json.loads(source.read_text())

def c(value):
    return json.dumps(value, ensure_ascii=False)

lines = ['/* Generated by tools/import-ajustes-pen.py from approved layout.json. */',
         'static const AjPenPage AJ_PEN_ADV[] = {']
for frame in frames:
    lines.append('  {' + ','.join([c(frame['title']), c(frame['secname']), str(frame['part']), str(frame['total'])]) + ', {')
    for col in frame['cols']:
        lines.append('    {' + ','.join([c(col['g']), str(col['x']), str(col['w']), str(len(col['rows']))]) + ', {')
        for row in col['rows']:
            icon = 'aj_' + row['ic']
            if not (root / 'deploy/app/art/icones' / (icon + '.png')).exists():
                icon = 'aj_sliders-horizontal'
            if row['id'] == 'AJ_BAIXAR_REGISTRO':
                lines.append('#ifdef NV_ANDROID')
            lines.append('      {' + ','.join([row['id'], c(row['t']), c(row['d']), c(icon), str(int(row['tg']))]) + '},')
            if row['id'] == 'AJ_BAIXAR_REGISTRO':
                lines.extend(['#else', '      {AJ_VER_REGISTRO,"Ver registro","Abra o registro desta sessão","aj_download",0},', '#endif'])
        lines.append('    }},')
    lines.append('  }},')
lines.append('};')
(root / 'src/ajustes_pen_avancados.inc').write_text('\n'.join(lines) + '\n')
